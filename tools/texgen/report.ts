import fs from 'node:fs'
/** assets.ts imports three, which the report does not need: read the registry rows as text (one row per line) so this runs with only tsx. */
interface A { id: string; kind: string; hi: string; lo?: string; tier: string; noMip?: boolean; preload?: boolean }
const ASSETS: A[] = fs.readFileSync('src/engine/assets.ts', 'utf8').split('\n').filter((l) => /^\s*\{ id: '/.test(l)).map((l) => {
  const g = (k: string) => l.match(new RegExp(k + ": (?:T \\+ )?'([^']+)'"))?.[1]
  const full = (k: string) => { const v = g(k); return v === undefined ? undefined : v.startsWith('/') ? v : '/textures/' + v }
  return { id: g('id')!, kind: g('kind')!, hi: full('hi')!, lo: full('lo'), tier: g('tier') ?? '', noMip: /noMip: true/.test(l), preload: !/preload: false/.test(l) }
})

/**
 * npm run textures:report: per-file weight table + totals for the desktop and mobile tiers.
 *  - transfer MB  = bytes on disk of the file that tier downloads
 *  - GPU MB (est.) = w*h*4 bytes (RGBA8) x 1.333 for mipmaps (strips and data are not mipmapped); a rough upper bound, no texture compression
 * Soft limits (reported, only the transfer limit fails the build): GPU desktop 900 MB, GPU mobile 300 MB.
 * Writes docs/TEXTURE_REPORT.md as well, so later sessions can diff it.
 */
interface Row { file: string; w: number; h: number; bytes: number; channels: number }
const rows = JSON.parse(fs.readFileSync('public/textures/manifest.json', 'utf8')) as Row[]
const by = new Map(rows.map((r) => ['/textures/' + r.file, r]))
const MB = 1048576
const lines: string[] = []
let dT = 0, mT = 0, dG = 0, mG = 0
const gpu = (r: Row, noMip: boolean | undefined) => (r.channels === 0 ? 0 : (r.w * r.h * 4 * (noMip || r.h <= 16 ? 1 : 4 / 3)) / MB)
const tbl: Array<[string, string, string, string, number, number, number, number]> = []
let fail = 0
for (const a of ASSETS.filter((x) => x.preload !== false)) {
  if (a.kind === 'data') { const d = by.get(a.hi); if (d) { dT += d.bytes; mT += d.bytes; tbl.push([a.id, a.tier, `${d.w} items`, `${d.w} items`, d.bytes / MB, d.bytes / MB, 0, 0]) } else { console.log(`FAIL ${a.id}: not in manifest.json`); fail++ } continue }
  const hi = by.get(a.hi), lo = by.get(a.lo ?? a.hi)
  if (!hi || !lo) { console.log(`FAIL ${a.id}: not in manifest.json`); fail++; continue }
  if ((a.tier === 'hi') !== !!a.lo) { console.log(`FAIL ${a.id}: tier '${a.tier}' does not match lo=${a.lo}`); fail++ }
  if (!fs.existsSync('public' + a.hi) || !fs.existsSync('public' + (a.lo ?? a.hi))) { console.log(`FAIL ${a.id}: file missing on disk`); fail++ }
  const gh = gpu(hi, a.noMip), gl = gpu(lo, a.noMip)
  dT += hi.bytes; mT += lo.bytes; dG += gh; mG += gl
  tbl.push([a.id, a.tier, `${hi.w}x${hi.h}`, `${lo.w}x${lo.h}`, hi.bytes / MB, lo.bytes / MB, gh, gl])
  if (Math.max(lo.w, lo.h) > 2048 && !a.noMip) { console.log(`FAIL ${a.id}: mobile file ${lo.w}x${lo.h} exceeds 2k`); fail++ }
}
tbl.sort((a, b) => b[4] - a[4])
const f = (n: number) => n.toFixed(2)
lines.push('| id | tier | desktop file | mobile file | desktop MB | mobile MB | GPU MB desk | GPU MB mob |', '|---|---|---|---|---|---|---|---|')
for (const t of tbl) lines.push(`| ${t[0]} | ${t[1]} | ${t[2]} | ${t[3]} | ${f(t[4])} | ${f(t[5])} | ${f(t[6])} | ${f(t[7])} |`)
lines.push(`| **TOTAL** | | | | **${f(dT / MB)}** (limit 60) | **${f(mT / MB)}** | **${f(dG)}** (soft 900) | **${f(mG)}** (soft 300) |`)
const text = lines.join('\n')
console.log(text)
if (dT > 60 * MB) { console.log('FAIL desktop transfer over 60 MB'); fail++ }
if (dG > 900) console.log('WARN desktop GPU estimate over the 900 MB soft limit')
if (mG > 300) console.log('WARN mobile GPU estimate over the 300 MB soft limit')
fs.writeFileSync('docs/TEXTURE_REPORT.md', `# TEXTURE REPORT\n\n> Generated by \`npm run textures:report\`. Do not edit by hand. GPU figures are RGBA8 + mipmaps estimates (no compression).\n\n${text}\n`)
process.exit(fail ? 1 : 0)
