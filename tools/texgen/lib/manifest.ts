import fs from 'node:fs'
import path from 'node:path'
import { OUT_DIR } from './io'

/** One row per texture file. Written to public/textures/manifest.json (read by the app) and docs/ASSETS.md. */
export interface AssetRecord {
  file: string
  w: number
  h: number
  channels: number
  bytes: number
  kind: 'real' | 'procedural'
  generator: string
  zone: string
  usage: string
  credit: string
  /** 'core' = loaded on every tier; 'hi' = desktop only (a smaller `fallback` file is loaded on mobile); 'mid' = optional intermediate file, not preloaded, not counted. */
  tier: 'core' | 'hi' | 'mid'
  fallback?: string
  colorSpace: 'srgb' | 'linear'
  note?: string
}

const REG = path.join(OUT_DIR, '.records.json')
export function loadRecords(): Record<string, AssetRecord> {
  return fs.existsSync(REG) ? JSON.parse(fs.readFileSync(REG, 'utf8')) : {}
}
export function saveRecord(r: AssetRecord) {
  const all = loadRecords()
  all[r.file] = r
  fs.writeFileSync(REG, JSON.stringify(all, null, 1))
}

export function writeManifest() {
  const all = Object.values(loadRecords()).sort((a, b) => a.file.localeCompare(b.file))
  const missing = all.filter((r) => !fs.existsSync(path.join(OUT_DIR, r.file)))
  const live = all.filter((r) => fs.existsSync(path.join(OUT_DIR, r.file)))
  for (const r of live) r.bytes = fs.statSync(path.join(OUT_DIR, r.file)).size
  fs.writeFileSync(path.join(OUT_DIR, 'manifest.json'), JSON.stringify(live, null, 1))
  const mb = (n: number) => (n / 1048576).toFixed(2)
  const desktop = live.filter((r) => r.tier === 'core' || r.tier === 'hi')
  const mobile = live.filter((r) => r.tier === 'core' || (r.tier === 'hi' && false)).concat(live.filter((r) => r.tier === 'hi' && r.fallback).map((r) => live.find((x) => x.file === r.fallback)!).filter(Boolean))
  const sum = (l: AssetRecord[]) => l.reduce((s, r) => s + r.bytes, 0)
  const rows = live.map((r) => `| \`${r.file}\` | ${r.w}×${r.h} | **${r.kind}** | ${r.generator} | ${r.zone} | ${r.usage} | ${r.credit} | ${mb(r.bytes)} MB |`)
  const doc = `# ASSETS

> Generated by \`npm run textures\` (tools/texgen/lib/manifest.ts) from \`public/textures/.records.json\`. Do not edit the table by hand.

## Policy

- **Procedural images are labelled \`procedural\`.** They are generated by code in \`tools/texgen\` from fixed seeds, never downloaded. Re-running \`npm run textures\` is idempotent and byte-stable for the same code + seeds.
- **Earth and Moon textures are \`real\` (NASA-derived)** and were taken from the old Astra project's \`src/assets\`. **CREDIT CHECK STILL NEEDED:** the old project did not record the exact NASA source product (likely Blue Marble / LROC-derived) or its licence note. Before launch, confirm the exact source, keep the "Image: NASA" credit line on the credits page, and replace this flag with the verified source. Until then these files carry \`credit-needed\`.
- No other image is downloaded. One network attempt for real NASA textures is permitted per project; if it fails it is never retried or blocked on (see HANDOFF.md). Result of that attempt: see "Network attempt" below.
- Texture budget: desktop payload ≤ 60 MB, mobile tier ≤ 2k per map. Enforced by \`npm run check:budget\`.
- Venus's radar-style surface map is for the credits page / reference only: it is not used by any 3D object.

## Budget

- Desktop payload (all manifest files): **${mb(sum(desktop))} MB** of 60 MB
- Mobile payload (2k tier: fallbacks substituted for \`hi\` files): **${mb(sum(mobile))} MB**

${'${REALISM}'}

## Files

| file | resolution | real / procedural | generator | zone | usage | credit | size |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}
${missing.length ? `\n> Missing files listed in the registry (regenerate): ${missing.map((m) => m.file).join(', ')}\n` : ''}
## Network attempt

See the section at the end of this file (appended by the one-time attempt, if made).
`
  const keep = fs.existsSync('docs/ASSETS.md') ? fs.readFileSync('docs/ASSETS.md', 'utf8') : ''
  const rs = keep.indexOf('<!-- REALISM-START -->'), re = keep.indexOf('<!-- REALISM-END -->')
  const src = 'tools/texgen/data/realism.md'
  const realism = fs.existsSync(src) ? fs.readFileSync(src, 'utf8').trim() : rs >= 0 && re > rs ? keep.slice(rs, re + '<!-- REALISM-END -->'.length) : '<!-- REALISM-START -->\n(no realism ratings written yet)\n<!-- REALISM-END -->'
  const tail = keep.includes('<!-- NETWORK-ATTEMPT -->') ? keep.slice(keep.indexOf('<!-- NETWORK-ATTEMPT -->')) : ''
  fs.writeFileSync('docs/ASSETS.md', doc.replace('${REALISM}', realism).replace(/## Network attempt[\s\S]*$/, '## Network attempt\n\n') + (tail || '<!-- NETWORK-ATTEMPT -->\nNot yet attempted.\n'))
  return { desktop: sum(desktop), mobile: sum(mobile) }
}
